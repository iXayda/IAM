CREATE TABLE iam_administrator_recovery (
    user_id UUID PRIMARY KEY REFERENCES iam_administrator (user_id) ON DELETE CASCADE,
    recovery_id UUID NOT NULL UNIQUE,
    old_factor_id UUID NOT NULL,
    new_factor_id UUID NOT NULL UNIQUE,
    credential_version BIGINT NOT NULL,
    token_digest VARCHAR(64) COLLATE "C" NOT NULL,
    secret_ciphertext VARCHAR(67) COLLATE "C" NOT NULL,
    key_id VARCHAR(64) COLLATE "C" NOT NULL,
    actor VARCHAR(128) COLLATE "C" NOT NULL,
    source VARCHAR(64) COLLATE "C" NOT NULL,
    correlation_id UUID NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT iam_administrator_recovery_factor FOREIGN KEY (user_id, old_factor_id)
        REFERENCES iam_user_totp (user_id, factor_id) ON DELETE CASCADE,
    CONSTRAINT iam_administrator_recovery_distinct_factor CHECK (old_factor_id <> new_factor_id),
    CONSTRAINT iam_administrator_recovery_version CHECK (credential_version > 0),
    CONSTRAINT iam_administrator_recovery_digest CHECK (token_digest ~ '^[0-9a-f]{64}$'),
    CONSTRAINT iam_administrator_recovery_secret CHECK (secret_ciphertext ~ '^v1\.[A-Za-z0-9_-]{64}$'),
    CONSTRAINT iam_administrator_recovery_key CHECK (key_id ~ '^[0-9a-f]{64}$'),
    CONSTRAINT iam_administrator_recovery_actor CHECK (actor ~ '^deployment:[a-zA-Z0-9][a-zA-Z0-9._-]{0,63}$'),
    CONSTRAINT iam_administrator_recovery_source CHECK (source ~ '^deployment:admin-recovery:[a-zA-Z0-9][a-zA-Z0-9._-]{0,31}$'),
    CONSTRAINT iam_administrator_recovery_time CHECK (isfinite(issued_at) AND isfinite(expires_at)
        AND expires_at = issued_at + INTERVAL '10 minutes')
);

CREATE INDEX iam_administrator_recovery_cleanup_idx ON iam_administrator_recovery (expires_at);

