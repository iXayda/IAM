CREATE TABLE iam_resource_role (
    id UUID PRIMARY KEY,
    resource_id UUID NOT NULL REFERENCES iam_resource(id),
    code VARCHAR(64) COLLATE "C" NOT NULL,
    display_name VARCHAR(128) NOT NULL,
    status VARCHAR(16) COLLATE "C" NOT NULL DEFAULT 'active',
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (resource_id, code),
    CONSTRAINT iam_resource_role_code CHECK (code ~ '^[a-z][a-z0-9_]{0,63}$'),
    CONSTRAINT iam_resource_role_display CHECK (char_length(display_name) >= 1 AND display_name IS NFC NORMALIZED),
    CONSTRAINT iam_resource_role_status CHECK (status IN ('active', 'disabled')),
    CONSTRAINT iam_resource_role_version CHECK (version >= 1),
    CONSTRAINT iam_resource_role_time CHECK (isfinite(created_at) AND isfinite(updated_at) AND updated_at >= created_at)
);
CREATE INDEX iam_resource_role_parent_created_id_idx ON iam_resource_role (resource_id, created_at, id);
CREATE INDEX iam_resource_role_parent_status_created_id_idx ON iam_resource_role (resource_id, status, created_at, id);

CREATE FUNCTION iam_protect_resource_role_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'resource role identities cannot be deleted';
    END IF;
    IF NEW.id IS DISTINCT FROM OLD.id OR NEW.resource_id IS DISTINCT FROM OLD.resource_id
        OR NEW.code IS DISTINCT FROM OLD.code OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'resource role identity and code are immutable';
    END IF;
    IF NEW.version <> OLD.version + 1 OR NEW.updated_at < OLD.updated_at THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'resource role updates require the next version and monotonic time';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER iam_resource_role_identity_protection BEFORE UPDATE OR DELETE ON iam_resource_role
    FOR EACH ROW EXECUTE FUNCTION iam_protect_resource_role_identity();

