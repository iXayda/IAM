CREATE TABLE iam_password_recovery_limit (
    dimension VARCHAR(16) NOT NULL,
    subject_key VARCHAR(64) COLLATE "C" NOT NULL,
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    failures INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (dimension, subject_key),
    CONSTRAINT iam_password_recovery_dimension CHECK (dimension IN ('source', 'account')),
    CONSTRAINT iam_password_recovery_key CHECK (subject_key ~ '^[0-9a-f]{64}$'),
    CONSTRAINT iam_password_recovery_time CHECK (isfinite(window_started_at)),
    CONSTRAINT iam_password_recovery_failures CHECK (
        failures >= 0 AND failures <= CASE dimension WHEN 'account' THEN 5 ELSE 30 END
    )
);

