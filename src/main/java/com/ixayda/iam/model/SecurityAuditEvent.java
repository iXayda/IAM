package com.ixayda.iam.model;

import java.util.Objects;
import java.util.UUID;

/** An identity operation to append; PostgreSQL assigns its recording time. */
public record SecurityAuditEvent(UUID id, Action action, UUID targetUserId, SecurityAuditContext context, SecurityAuditTarget target) {

	public SecurityAuditEvent(UUID id, Action action, UUID targetUserId, SecurityAuditContext context) {
		this(id, action, targetUserId, context, null);
	}

	public SecurityAuditEvent {
		Objects.requireNonNull(id, "Audit event id is required");
		Objects.requireNonNull(action, "Audit action is required");
		if (action.targetType() != null) {
			if (target == null || target.type() != action.targetType() || targetUserId != null) {
				throw new IllegalArgumentException("Audit object target is required and must match the action");
			}
		}
		else if (target != null) { throw new IllegalArgumentException("Audit action does not accept an object target"); }
		if (targetUserId == null && action.requiresTarget()) {
			throw new IllegalArgumentException("Audit target user id is required");
		}
		Objects.requireNonNull(context, "Audit context is required");
	}

	public enum Action {
		USER_CREATED, INITIAL_PASSWORD_SET, ACCOUNT_SETUP_ISSUED, ACCOUNT_SETUP_CANCELLED, ACCOUNT_SETUP_COMPLETED,
		ACCOUNT_SETUP_FAILED, ACCOUNT_SETUP_THROTTLED,
		PASSWORD_AUTHENTICATED, PASSWORD_AUTH_FAILED, PASSWORD_AUTH_THROTTLED,
		BROWSER_SESSION_CREATED, BROWSER_SESSION_ENDED, BROWSER_ENTRY_THROTTLED,
		PASSWORD_CHANGED, PASSWORD_CHANGE_FAILED, PASSWORD_CHANGE_THROTTLED, BROWSER_SESSIONS_REVOKED,
		PASSWORD_RECOVERY_ISSUED, PASSWORD_RECOVERY_CANCELLED, PASSWORD_RECOVERY_COMPLETED, PASSWORD_RECOVERY_FAILED, PASSWORD_RECOVERY_THROTTLED,
		USER_PROFILE_UPDATED, USER_DISABLED, USER_ENABLED,
		TOTP_ENROLLMENT_STARTED, TOTP_ENROLLMENT_CANCELLED, TOTP_ENROLLMENT_COMPLETED,
		TOTP_ENROLLMENT_FAILED, TOTP_ENROLLMENT_THROTTLED, TOTP_AUTHENTICATED, TOTP_AUTH_FAILED, TOTP_AUTH_THROTTLED,
		MFA_RECOVERY_CODES_GENERATED, MFA_RECOVERY_CODE_CONSUMED, MFA_RECOVERY_CODE_FAILED, MFA_RECOVERY_CODE_THROTTLED,
		TOTP_RECOVERY_STARTED, TOTP_RECOVERY_COMPLETED, TOTP_RECOVERY_FAILED, TOTP_RECOVERY_THROTTLED,
		TOTP_REPLACEMENT_STARTED, TOTP_REPLACEMENT_COMPLETED, TOTP_REPLACEMENT_FAILED, TOTP_REPLACEMENT_THROTTLED,
		ADMIN_BOOTSTRAP_PREPARED, ADMIN_BOOTSTRAP_COMPLETED, ADMIN_BOOTSTRAP_REJECTED, ADMIN_BOOTSTRAP_THROTTLED, LAST_ADMINISTRATOR_PROTECTED,
		ADMIN_MFA_AUTHENTICATED, ADMIN_MFA_REJECTED, ADMIN_ACCESS_DENIED,
		ADMIN_RECOVERY_STARTED, ADMIN_RECOVERY_COMPLETED, ADMIN_RECOVERY_REJECTED, ADMIN_RECOVERY_THROTTLED,
		SIGNING_KEY_INITIALIZED,
		RESOURCE_CREATED, RESOURCE_UPDATED, RESOURCE_DISABLED, RESOURCE_ENABLED,
		RESOURCE_ROLE_CREATED, RESOURCE_ROLE_UPDATED, RESOURCE_ROLE_DISABLED, RESOURCE_ROLE_ENABLED;

		public SecurityAuditTarget.Type targetType() {
			return switch (this) {
				case RESOURCE_ROLE_CREATED, RESOURCE_ROLE_UPDATED, RESOURCE_ROLE_DISABLED, RESOURCE_ROLE_ENABLED -> SecurityAuditTarget.Type.ROLE;
				case RESOURCE_CREATED, RESOURCE_UPDATED, RESOURCE_DISABLED, RESOURCE_ENABLED -> SecurityAuditTarget.Type.RESOURCE;
				default -> null;
			};
		}

		public boolean isFailure() {
			return this == PASSWORD_AUTH_FAILED || this == PASSWORD_AUTH_THROTTLED || this == BROWSER_ENTRY_THROTTLED
					|| this == ACCOUNT_SETUP_FAILED || this == ACCOUNT_SETUP_THROTTLED
					|| this == PASSWORD_CHANGE_FAILED || this == PASSWORD_CHANGE_THROTTLED || this == PASSWORD_RECOVERY_FAILED || this == PASSWORD_RECOVERY_THROTTLED
					|| this == TOTP_ENROLLMENT_FAILED || this == TOTP_ENROLLMENT_THROTTLED
					|| this == TOTP_AUTH_FAILED || this == TOTP_AUTH_THROTTLED
					|| this == MFA_RECOVERY_CODE_FAILED || this == MFA_RECOVERY_CODE_THROTTLED
					|| this == TOTP_RECOVERY_FAILED || this == TOTP_RECOVERY_THROTTLED
					|| this == TOTP_REPLACEMENT_FAILED || this == TOTP_REPLACEMENT_THROTTLED
					|| this == ADMIN_BOOTSTRAP_REJECTED || this == ADMIN_BOOTSTRAP_THROTTLED || this == LAST_ADMINISTRATOR_PROTECTED
					|| this == ADMIN_MFA_REJECTED || this == ADMIN_ACCESS_DENIED
					|| this == ADMIN_RECOVERY_REJECTED || this == ADMIN_RECOVERY_THROTTLED;
		}

		public boolean requiresTarget() {
			return targetType() == null && this != PASSWORD_AUTH_FAILED && this != PASSWORD_AUTH_THROTTLED && this != BROWSER_ENTRY_THROTTLED
					&& this != ACCOUNT_SETUP_FAILED && this != ACCOUNT_SETUP_THROTTLED
					&& this != PASSWORD_RECOVERY_FAILED && this != PASSWORD_RECOVERY_THROTTLED && this != TOTP_ENROLLMENT_FAILED && this != TOTP_ENROLLMENT_THROTTLED
					&& this != TOTP_AUTH_FAILED && this != TOTP_AUTH_THROTTLED
					&& this != MFA_RECOVERY_CODE_FAILED && this != MFA_RECOVERY_CODE_THROTTLED
					&& this != TOTP_RECOVERY_FAILED && this != TOTP_RECOVERY_THROTTLED
					&& this != TOTP_REPLACEMENT_FAILED && this != TOTP_REPLACEMENT_THROTTLED
					&& this != ADMIN_BOOTSTRAP_THROTTLED && this != ADMIN_ACCESS_DENIED
					&& this != ADMIN_RECOVERY_REJECTED && this != ADMIN_RECOVERY_THROTTLED && this != SIGNING_KEY_INITIALIZED;
		}
	}

}
